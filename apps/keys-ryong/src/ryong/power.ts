// Turning a keyboard off and on, as keys.ryong.com shows and edits it.
//
// - Off: ZMK's Soft Off behavior, wherever the keymap puts it. Found in the keymap file, or live on the
//   connected keyboard (which includes changes made in the editor).
// - Wake: after a Soft Off only one key wakes the chip. That is wiring: a pair of matrix pins in the
//   devicetree. Keyboards set up for this keep a ryong-power.json next to their keymap with the matrix
//   (pins per key position), so the site can write the wake key's devicetree file (ryong-wake.dtsi) and
//   the position the firmware's turn-on check uses (CONFIG_RYONG_WAKE_POSITION).
// - On: the firmware's check wants the wake key + a Soft Off key held for 3 s.

import { commitFiles, readFile } from "./api";
import type { Board } from "./keyboards";
import { dirOf } from "./behaviors/keymapFile";
import { keyName } from "./unlockHint";
import { t } from "./i18n";

export interface PowerDoc {
  format: "ryong-power";
  version: 1;
  /** key position that wakes the keyboard after a Soft Off */
  wake: number;
  /** the physical layout the positions below belong to */
  layout: string;
  diode: "col2row" | "row2col";
  /** e.g. "&gpio0 22" */
  rows: string[];
  cols: string[];
  /** [row, col] for each key position */
  positions: [number, number][];
  /** files this writes, from the repository root */
  dtsi: string;
  conf: string;
  /** the board's own defaults for on/off firmware features (CONFIG_… without the prefix: "y"/"n"/value) */
  defaults?: Record<string, string>;
  /** lights the board has: "backlight", "underglow" */
  hardware?: string[];
}

export const POWER_FILE = "ryong-power.json";
export const powerPath = (b: Board) => `${dirOf(b.keymap)}${POWER_FILE}`;

export async function readPower(b: Board): Promise<PowerDoc | null> {
  const t = await readFile(b.repo, b.branch, powerPath(b)).catch(() => null);
  if (!t) return null;
  try {
    const d = JSON.parse(t) as PowerDoc;
    return d.format === "ryong-power" ? d : null;
  } catch {
    return null;
  }
}

/** The devicetree for "only this key wakes the keyboard" (ZMK's wakeup-only key switch). */
export function wakeDtsi(d: PowerDoc): string {
  const [r, c] = d.positions[d.wake];
  // the line the diodes lead into is read; the other one is powered while the keyboard is off
  const [sense, drive] = d.diode === "col2row" ? [d.rows[r], d.cols[c]] : [d.cols[c], d.rows[r]];
  return `/*
 * Generated by keys.ryong.com — change the wake key on the site (Firmware → edit), not by hand.
 * After a Soft Off only key position ${d.wake} (row ${r}, column ${c}) wakes the keyboard;
 * the firmware then asks for it together with a Soft Off key, held 3 s.
 */

/ {
    ryong_wake_keys {
        compatible = "gpio-keys";
        ryong_wake_key: ryong_wake_key {
            gpios = <${sense} (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>;
        };
    };

    ryong_waker: ryong_waker {
        compatible = "zmk,gpio-key-wakeup-trigger";
        trigger = <&ryong_wake_key>;
        wakeup-source;
        extra-gpios = <${drive} GPIO_ACTIVE_HIGH>;
    };

    soft_off_wakers {
        compatible = "zmk,soft-off-wakeup-sources";
        wakeup-sources = <&ryong_waker>;
    };
};
`;
}

const WAKE_LINE = /^[ \t]*CONFIG_RYONG_WAKE_POSITION[ \t]*=.*$/m;
export function withWakeConf(conf: string, pos: number) {
  const line = `CONFIG_RYONG_WAKE_POSITION=${pos}`;
  if (WAKE_LINE.test(conf)) return conf.replace(WAKE_LINE, line);
  return `${conf.trimEnd() ? conf.trimEnd() + "\n\n" : ""}# Key that wakes the keyboard after Soft Off (set on keys.ryong.com)\n${line}\n`;
}

/** Save a new wake key: devicetree, config line and the json, in one commit (starts a build). */
export async function saveWake(b: Board, d: PowerDoc, pos: number, keyLabel: string) {
  const next = { ...d, wake: pos };
  const conf = (await readFile(b.repo, b.branch, d.conf)) ?? "";
  await commitFiles(
    b.repo,
    b.branch,
    [
      { path: powerPath(b), content: JSON.stringify(next, null, 2) + "\n" },
      { path: d.dtsi, content: wakeDtsi(next) },
      { path: d.conf, content: withWakeConf(conf, pos) },
    ],
    `Wake key: ${keyLabel} (position ${pos})\n\nSaved from keys.ryong.com`
  );
  return next;
}

// ---------- where Soft Off is, from the keymap file ----------

export interface PowerKeys {
  /** to turn off, e.g. ["Fn", "Left Ctrl"] */
  off: string[];
  /** key positions holding Soft Off */
  positions: number[];
  /** the wake key's name, e.g. "Fn" */
  wake?: string;
}

function parseLayers(src: string) {
  const text = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
  const defines: Record<string, string> = {};
  for (const m of text.matchAll(/^\s*#define\s+(\w+)\s+(\S+)/gm)) defines[m[1]] = m[2];
  const km = text.indexOf('"zmk,keymap"');
  const layers: string[][][] = [];
  const names: string[] = [];
  if (km < 0) return { layers, defines, names };
  for (const m of text.slice(km).matchAll(/([\w-]+)\s*\{([^{}]*)\}/g)) {
    const b = m[2].match(/bindings\s*=\s*<([^>]*)>/);
    if (!b || /key-positions|compatible/.test(m[2])) continue;
    const out: string[][] = [];
    for (const t of b[1].trim().split(/\s+/)) {
      if (t.startsWith("&")) out.push([t]);
      else if (out.length) out[out.length - 1].push(t);
    }
    layers.push(out);
    names.push(m[2].match(/(?:display-name|label)\s*=\s*"([^"]*)"/)?.[1] ?? m[1].replace(/_layer$/, ""));
  }
  return { layers, defines, names };
}

const SHORT: Record<string, string> = {
  "Left Ctrl": "LCtrl", "Right Ctrl": "RCtrl", "Left Shift": "LShift", "Right Shift": "RShift", "Left Alt": "LAlt", "Right Alt": "RAlt",
  "Left Cmd/Win": "LGUI", "Right Cmd/Win": "RGUI", "Caps Lock": "Caps", Backspace: "Bksp", Delete: "Del", "Page Up": "PgUp", "Page Down": "PgDn",
  "Print Screen": "PrtSc", Insert: "Ins",
};
export const shortKey = (s: string) => SHORT[s] ?? s;

export interface KeyLabel {
  /** what the key types or does */
  main: string;
  /** what holding it does, e.g. the layer it switches to */
  sub?: string;
}

/** What each key on the base layer does, from the keymap file. */
export function baseLabels(src: string): KeyLabel[] {
  const { layers, defines, names } = parseLayers(src);
  const layer = (p?: string) => {
    const n = Number(defines[p ?? ""] ?? p);
    return names[n] ?? `layer ${n}`;
  };
  return (layers[0] ?? []).map((b) => {
    const kn = keyName(b);
    switch (b[0]) {
      case "&mo": return { main: "Fn", sub: layer(b[1]) };
      case "&lt": return { main: shortKey(kn ?? "?"), sub: t("hold: {l}", "홀드: {l}", { l: layer(b[1]) }) };
      case "&mt": return { main: shortKey(kn ?? "?"), sub: t("hold: mod", "홀드: 모디") };
      case "&tog": return { main: "Tog", sub: layer(b[1]) };
      case "&to": return { main: "To", sub: layer(b[1]) };
      case "&sl": return { main: "Sticky", sub: layer(b[1]) };
      default: return { main: kn ? shortKey(kn) : b[0].replace(/^&/, "") };
    }
  });
}

/** Name of the key at a base-layer position; a key that only switches layers is "Fn". */
export function baseKeyName(src: string, pos: number): string {
  const { layers } = parseLayers(src);
  const b = layers[0]?.[pos];
  if (!b) return `#${pos + 1}`;
  if (["&mo", "&tog", "&to", "&sl"].includes(b[0])) return "Fn";
  return keyName(b) || `#${pos + 1}`;
}

export type At = { layer: number; pos: number };

/** Where a behavior sits in the keymap file: [{ layer, pos }] */
export function findInKeymap(src: string, behavior: string): At[] {
  const { layers } = parseLayers(src);
  return layers.flatMap((l, li) => l.map((b, p) => (b[0] === behavior ? { layer: li, pos: p } : null)).filter((x): x is At => !!x));
}

/** The keys to press for the first of `at`, e.g. ["Fn", "Enter"] (layer key + the key in that spot). */
export function keysAt(src: string, at: At[]): string[] | null {
  if (!at.length) return null;
  const { layers, defines } = parseLayers(src);
  const first = at[0];
  const key = baseKeyName(src, first.pos);
  if (first.layer === 0 || !layers.length) return [key];
  const base = layers[0];
  const j = base.findIndex((b) => ["&mo", "&lt"].includes(b[0]) && Number(defines[b[1]] ?? b[1]) === first.layer);
  if (j < 0) return [key];
  return [base[j][0] === "&lt" ? keyName(base[j]) || `#${j + 1}` : "Fn", key];
}

/** Key positions for the first of `at`: [layer key, key] or [key]. */
export function positionsAt(src: string, at: At[]): number[] | null {
  if (!at.length) return null;
  const { layers, defines } = parseLayers(src);
  const first = at[0];
  if (first.layer === 0 || !layers.length) return [first.pos];
  const j = layers[0].findIndex((b) => ["&mo", "&lt"].includes(b[0]) && Number(defines[b[1]] ?? b[1]) === first.layer);
  return j < 0 ? [first.pos] : [j, first.pos];
}

export function powerFromKeymap(src: string, softOffAt?: At[], wake?: number): PowerKeys | null {
  const at = softOffAt ?? findInKeymap(src, "&soft_off");
  const off = keysAt(src, at);
  if (!off) return null;
  return { off, positions: [...new Set(at.map((x) => x.pos))], wake: wake === undefined ? undefined : baseKeyName(src, wake) };
}
