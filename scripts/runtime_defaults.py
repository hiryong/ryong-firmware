"""Turn firmware-built combos and macros (ryong-behaviors.dtsi from keys.ryong.com) into
runtime defaults, so the web app lists and edits them.

    python3 scripts/runtime_defaults.py <ryong-behaviors.dtsi> <out.overlay> [ryong-behaviors.json]

- `zmk,combos` children   -> one `cormoran,runtime-combo-defaults` node (same keys/binding/timeout),
                             and the original combos node is deleted (no double trigger).
- `zmk,behavior-macro` X  -> a `cormoran,runtime-macro-default` with the same steps, and X itself
                             becomes `ryong,behavior-named-runtime-macro` playing that macro by name,
                             so every `&X` in the keymap keeps working and follows edits.
Device names stay the same, so behavior local IDs (and saved keymaps) are unaffected.
"""
import json
import re
import sys
from pathlib import Path

NAME_MAX = 24  # CONFIG_ZMK_RUNTIME_MACRO_NAME_MAX_LEN default; checked again by the module


def block(text, start):
    """Text between the '{' at/after start and its matching '}'."""
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j], j
    raise SystemExit("Unbalanced braces in behaviors file")


def prop(body, name):
    m = re.search(r"(?m)^\s*" + re.escape(name) + r"\s*=\s*(.*?);\s*$", body, re.S)
    return m.group(1).strip() if m else None


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", text), flags=re.S)


def convert(dtsi, names=None):
    text = strip_comments(dtsi)
    names = names or {}
    out = ["/* Generated by scripts/runtime_defaults.py — firmware combos/macros as editable runtime defaults. */", "/ {"]
    patches = []

    combos = []
    m = re.search(r"\bcombos\s*\{", text)
    if m:
        body, _ = block(text, m.end() - 1)
        if 'compatible = "zmk,combos"' not in body:
            raise SystemExit("combos node is not zmk,combos")
        for c in re.finditer(r"(\w+)\s*\{", body):
            child, _ = block(body, c.end() - 1)
            keys, binding = prop(child, "key-positions"), prop(child, "bindings")
            if not keys or not binding:
                raise SystemExit(f"combo {c.group(1)}: key-positions and bindings are required")
            lines = [f"key-positions = {keys};", f"bindings = {binding};"]
            for p in ("timeout-ms", "layers", "require-prior-idle-ms"):
                v = prop(child, p)
                if v:
                    lines.append(f"{p} = {v};")
            display = (names.get(c.group(1)) or c.group(1))[:63].replace('"', "'")
            lines.append(f'display-name = "{display}";')
            combos.append((c.group(1), lines))
        out.append("    /delete-node/ combos;")
    if combos:
        out.append("    ry_runtime_combo_defaults {")
        out.append('        compatible = "cormoran,runtime-combo-defaults";')
        for name, lines in combos:
            out.append(f"        {name} {{")
            out += [f"            {l}" for l in lines]
            out.append("        };")
        out.append("    };")

    seen = set()
    for mm in re.finditer(r"(\w+)\s*:\s*(\w+)\s*\{", text):
        body, _ = block(text, mm.end() - 1)
        if '"zmk,behavior-macro"' not in body:
            continue
        label = mm.group(1)
        if prop(body, "#binding-cells") != "<0>":
            raise SystemExit(f"macro {label}: only parameterless macros can become runtime macros")
        macro_name = (prop(body, "display-name") or f'"{label}"').strip('"')
        if len(macro_name.encode()) > NAME_MAX:
            raise SystemExit(f"macro {label}: name '{macro_name}' is longer than {NAME_MAX} bytes")
        if macro_name in seen:
            raise SystemExit(f"duplicate macro name '{macro_name}'")
        seen.add(macro_name)
        steps = prop(body, "bindings")
        if not steps:
            raise SystemExit(f"macro {label}: no bindings")
        steps = " ".join(steps.split())
        node = "ry_rmd_" + label.lower()
        out.append(f"    {node} {{")
        out.append('        compatible = "cormoran,runtime-macro-default";')
        out.append(f'        macro-name = "{macro_name}";')
        wait = prop(body, "wait-ms")
        if wait:
            out.append(f"        wait-ms = {wait};")
        out.append(f"        bindings = {steps};")
        out.append("    };")
        patches += [f"&{label} {{", '    compatible = "ryong,behavior-named-runtime-macro";', f'    macro-name = "{macro_name}";',
                    "    /delete-property/ bindings;", "    /delete-property/ wait-ms;", "    /delete-property/ tap-ms;", "};"]
    out.append("};")
    return "\n".join(out + patches) + "\n", len(combos), len(seen)


def json_names(path):
    if not path or not Path(path).is_file():
        return {}
    data = json.loads(Path(path).read_text())
    return {c["id"]: c["name"] for c in data.get("combos", []) if c.get("id") and c.get("name")}


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    overlay, nc, nm = convert(src.read_text(), json_names(sys.argv[3] if len(sys.argv) > 3 else None))
    dst.write_text(overlay)
    print(f"runtime defaults: {nc} combo(s), {nm} macro(s) -> {dst}")


if __name__ == "__main__":
    main()
